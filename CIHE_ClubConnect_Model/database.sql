CREATE DATABASE IF NOT EXISTS cihe_clubconnect CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cihe_clubconnect;

DROP TABLE IF EXISTS activity_logs;
DROP TABLE IF EXISTS announcements;
DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','user') NOT NULL DEFAULT 'user',
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE events (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(120) NOT NULL,
 description TEXT NOT NULL,
 category ENUM('Academic','Social','Sports','Career','Community') NOT NULL,
 location VARCHAR(150) NOT NULL,
 event_date DATETIME NOT NULL,
 created_by INT UNSIGNED NOT NULL,
 updated_by INT UNSIGNED NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_events_created FOREIGN KEY(created_by) REFERENCES users(id),
 CONSTRAINT fk_events_updated FOREIGN KEY(updated_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_event_date(event_date),
 INDEX idx_category(category),
 INDEX idx_title(title)
) ENGINE=InnoDB;

CREATE TABLE announcements (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(120) NOT NULL,
 body TEXT NOT NULL,
 created_by INT UNSIGNED NOT NULL,
 updated_by INT UNSIGNED NULL,
 published_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_ann_created FOREIGN KEY(created_by) REFERENCES users(id),
 CONSTRAINT fk_ann_updated FOREIGN KEY(updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE activity_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 action VARCHAR(40) NOT NULL,
 entity_type VARCHAR(40) NOT NULL,
 entity_id INT UNSIGNED NULL,
 details VARCHAR(255) NULL,
 ip_address VARCHAR(45) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_logs_user FOREIGN KEY(user_id) REFERENCES users(id),
 INDEX idx_logs_created(created_at)
) ENGINE=InnoDB;

